"""Entry point for Mini Git CLI.

Usage:
    python main.py
"""

# [1차]: 표준 시스템 모듈을 가져옵니다.
# [2차]: 프로그램의 출입문을 제어할 시스템 열쇠를 챙깁니다.
import sys

# [1차]: 대화형 REPL 제어기 클래스 MiniGitCLI를 가져옵니다.
# [2차]: 손님을 맞이할 메인 안내 데스크를 데려옵니다.
from minigit.cli import MiniGitCLI


# [1차]: 프로그램 실행의 엔트리포인트 함수를 정의합니다.
# [2차]: 하루의 영업을 시작하는 개장 스위치입니다.
def main() -> None:
    # [1차]: JSON 파일 영속화를 기본 지원하는 CLI 컨트롤러를 생성합니다.
    # [2차]: 프로그램을 종료해도 작업 내용이 보존되도록 영구 보관 파일철을 연결합니다.
    cli = MiniGitCLI(storage_path="minigit_repo.json")
    # [1차]: REPL 대화형 무한 루프를 가동합니다.
    # [2차]: 창구 문을 활짝 열고 손님들의 주문을 받기 시작합니다.
    cli.run_repl()


# [1차]: 본 파일이 직접 실행되었을 때(모듈 임포트가 아닐 때)만 main()을 구동합니다.
# [2차]: 남의 가게에 부품으로 불려간 게 아니라, 우리 가게 간판을 걸고 정식 오픈했을 때만 영업을 시작합니다.
if __name__ == "__main__":
    # [1차]: main 함수를 호출하여 프로그램을 시작합니다.
    # [2차]: 개장 징을 울리며 첫 손님을 맞이합니다.
    main()
